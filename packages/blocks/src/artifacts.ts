import type { Declaration } from "./declare";
import {
  creates,
  destroys,
  duration,
  noUndo,
  nothingToUndo,
  optional,
  reads,
  required,
  rerun,
  resource,
  text,
  writes,
} from "./declare";

export const repository = resource("artifacts.repository");
const token = resource("artifacts.token");

export const artifacts: ReadonlyArray<Declaration> = [
  {
    id: "artifacts.forkRepository",
    version: 1,
    title: "Fork a repository for one task",
    kind: "Action",
    inputs: { repository: required(repository), task: required(text) },
    outputs: { fork: repository },
    effects: [reads("repository"), creates("fork", "Temporary")],
    undo: noUndo(
      "The fork is temporary and tagged with its run. The recipe deletes it in a finally step, which the CleanedUp invariant checks.",
    ),
    rerun,
  },
  {
    id: "artifacts.issueToken",
    version: 1,
    title: "Issue a short-lived token scoped to a fork",
    kind: "Action",
    inputs: { fork: required(repository), validFor: required(duration) },
    outputs: { token },
    effects: [reads("fork"), creates("token", "Temporary")],
    undo: noUndo(
      "The token is temporary and tagged with its run. The recipe revokes it in a finally step, which the CleanedUp invariant checks.",
    ),
    rerun,
  },
  {
    id: "artifacts.awaitPush",
    version: 1,
    title: "Wait for work to be pushed to a fork",
    kind: "Action",
    inputs: { fork: required(repository), timeout: required(duration) },
    outputs: { commit: text },
    effects: [reads("fork")],
    undo: nothingToUndo,
    rerun,
  },
  {
    id: "artifacts.runChecks",
    version: 1,
    title: "Run checks on a commit",
    kind: "Check",
    inputs: { fork: required(repository), commit: required(text) },
    outputs: {},
    effects: [reads("fork")],
    undo: nothingToUndo,
    rerun,
  },
  {
    id: "artifacts.mergeFork",
    version: 1,
    title: "Merge a fork's commit and record it",
    kind: "Action",
    inputs: {
      repository: required(repository),
      fork: required(repository),
      commit: required(text),
    },
    outputs: {},
    effects: [writes("repository"), reads("fork")],
    undo: noUndo("A merge that others have fetched cannot be taken back."),
    rerun,
  },
  {
    id: "artifacts.revokeToken",
    version: 1,
    title: "Revoke a token",
    kind: "Action",
    inputs: { token: optional(token) },
    outputs: {},
    effects: [destroys("token")],
    undo: noUndo("A revoked token cannot be made valid again."),
    rerun,
  },
  {
    id: "artifacts.deleteFork",
    version: 1,
    title: "Delete a fork",
    kind: "Action",
    inputs: { fork: optional(repository) },
    outputs: {},
    effects: [destroys("fork")],
    undo: noUndo("A deleted fork and its commits cannot be brought back."),
    rerun,
  },
];
